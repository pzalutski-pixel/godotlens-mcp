"""Godot's binary Variant format, as the remote debugger link carries it.

A port of ``decode_variant``/``encode_variant`` in ``core/io/marshalls.cpp``, checked
byte for byte against what Godot itself produces (``tests/data/variant_golden.jsonl``,
generated by ``var_to_bytes``). Every value is a ``uint32`` header - type id in bits
0-7, flags above - followed by its payload, little-endian and padded to 4 bytes.

Python has no equivalent for most Godot types, so those decode to small value
classes that remember their Godot type and re-encode identically. Agents see values
as Godot literal text (``Vector2(1.5, 2)``), the same text ``var_to_str`` writes.
"""

from __future__ import annotations

import re
import struct
from dataclasses import dataclass
from typing import Any, NamedTuple

TYPE_NAMES = (
    "Nil", "bool", "int", "float", "String", "Vector2", "Vector2i", "Rect2", "Rect2i",
    "Vector3", "Vector3i", "Transform2D", "Vector4", "Vector4i", "Plane", "Quaternion",
    "AABB", "Basis", "Transform3D", "Projection", "Color", "StringName", "NodePath",
    "RID", "Object", "Callable", "Signal", "Dictionary", "Array", "PackedByteArray",
    "PackedInt32Array", "PackedInt64Array", "PackedFloat32Array", "PackedFloat64Array",
    "PackedStringArray", "PackedVector2Array", "PackedVector3Array", "PackedColorArray",
    "PackedVector4Array",
)
TYPE_IDS = {name: index for index, name in enumerate(TYPE_NAMES)}

# Header flags (marshalls.cpp).
_TYPE_MASK = 0xFF
_FLAG_64 = 1 << 16             # INT and FLOAT: 64-bit payload; math types: doubles
_FLAG_OBJECT_AS_ID = 1 << 16   # OBJECT: a uint64 instance id, as the debugger sends
_ARRAY_KIND_SHIFT = 16
_DICT_KEY_SHIFT = 16
_DICT_VALUE_SHIFT = 18
_KIND_NONE, _KIND_BUILTIN, _KIND_CLASS_NAME, _KIND_SCRIPT = 0, 1, 2, 3

# Fixed-size types: component count and kind. "f" is real_t (float32 in official
# builds, double when flagged), "i" int32, "c" always float32 (Color).
_FIXED = {
    "Vector2": (2, "f"), "Vector2i": (2, "i"), "Rect2": (4, "f"), "Rect2i": (4, "i"),
    "Vector3": (3, "f"), "Vector3i": (3, "i"), "Transform2D": (6, "f"),
    "Vector4": (4, "f"), "Vector4i": (4, "i"), "Plane": (4, "f"),
    "Quaternion": (4, "f"), "AABB": (6, "f"), "Basis": (9, "f"),
    "Transform3D": (12, "f"), "Projection": (16, "f"), "Color": (4, "c"),
}
# Packed arrays of fixed-size elements: components per element and kind.
_PACKED = {
    "PackedInt32Array": (1, "i"), "PackedInt64Array": (1, "q"),
    "PackedFloat32Array": (1, "f32"), "PackedFloat64Array": (1, "f64"),
    "PackedVector2Array": (2, "f"), "PackedVector3Array": (3, "f"),
    "PackedColorArray": (4, "c"), "PackedVector4Array": (4, "f"),
}

MAX_DEPTH = 512  # Variant::MAX_RECURSION_DEPTH
# The game allocates 8 MiB for an incoming message (RemoteDebuggerPeerTCP).
MAX_MESSAGE_BYTES = 8 << 20


class DecodeError(ValueError):
    """Bytes that are not a valid encoded Variant."""


# ---------------------------------------------------------------------------
# Value classes for Godot types Python lacks
# ---------------------------------------------------------------------------


class Value(NamedTuple):
    """A fixed-size Godot value (Vector2, Color, Transform3D, ...) and its components.

    Components are in Godot's own order, which is also the order its text form uses.
    """

    type: str
    components: tuple


class StringName(str):
    """A Godot StringName; written &"name"."""

    __slots__ = ()


class NodePath(str):
    """A Godot NodePath in text form: ``/root/Main``, ``Player/Gun:position:x``."""

    __slots__ = ()


@dataclass(frozen=True)
class ObjectId:
    """An object, as the debugger sends it: by instance id (0 is null)."""

    id: int


@dataclass(frozen=True)
class Rid:
    id: int


@dataclass(frozen=True)
class SignalRef:
    name: str
    object_id: int


@dataclass(frozen=True)
class CallableRef:
    """Godot sends a Callable with no payload; there is nothing to call."""


@dataclass(frozen=True)
class ContainerType:
    """The element type of a typed Array, or a key/value type of a typed Dictionary.

    ``kind`` is 1 for a builtin (``builtin`` holds its type id), 2 for a class name
    and 3 for a script path, both held in ``name``.
    """

    kind: int
    builtin: int = 0
    name: str = ""

    def text(self) -> str:
        return TYPE_NAMES[self.builtin] if self.kind == _KIND_BUILTIN else self.name


class GodotArray(list):
    """An Array that remembers its element type when it has one (``Array[int]``)."""

    def __init__(self, items=(), element: ContainerType | None = None):
        super().__init__(items)
        self.element = element


class GodotDict(dict):
    """A Dictionary that remembers its key and value types when it has them."""

    def __init__(self, items=(), key: ContainerType | None = None,
                 value: ContainerType | None = None):
        super().__init__(items)
        self.key_type = key
        self.value_type = value


@dataclass(frozen=True)
class Packed:
    """A packed array other than PackedByteArray (which decodes to ``bytes``).

    Vector and Color arrays hold one ``Value`` per element.
    """

    type: str
    items: tuple


# ---------------------------------------------------------------------------
# Decoding
# ---------------------------------------------------------------------------


class _Reader:
    def __init__(self, data: bytes | memoryview, offset: int):
        self.data = data
        self.pos = offset

    def take(self, size: int) -> bytes:
        if size < 0 or self.pos + size > len(self.data):
            raise DecodeError("truncated Variant")
        chunk = bytes(self.data[self.pos:self.pos + size])
        self.pos += size
        return chunk

    def u32(self) -> int:
        return struct.unpack("<I", self.take(4))[0]

    def i32(self) -> int:
        return struct.unpack("<i", self.take(4))[0]

    def string(self) -> str:
        length = self.i32()
        if length < 0:
            raise DecodeError("negative string length")
        text = self.take(length)
        self.take((4 - length % 4) % 4)
        try:
            return text.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise DecodeError(f"string is not UTF-8: {exc}") from None


def decode(data: bytes | memoryview, offset: int = 0) -> tuple[Any, int]:
    """Decode one Variant starting at ``offset``. Returns (value, offset after it)."""
    reader = _Reader(data, offset)
    value = _decode(reader, 0)
    return value, reader.pos


def _floats(reader: _Reader, count: int, wide: bool) -> tuple:
    fmt = "d" if wide else "f"
    return struct.unpack(f"<{count}{fmt}", reader.take(count * (8 if wide else 4)))


def _container_type(reader: _Reader, kind: int) -> ContainerType | None:
    if kind == _KIND_NONE:
        return None
    if kind == _KIND_BUILTIN:
        builtin = reader.u32()
        if builtin >= len(TYPE_NAMES):
            raise DecodeError(f"invalid container element type {builtin}")
        return ContainerType(_KIND_BUILTIN, builtin=builtin)
    return ContainerType(kind, name=reader.string())


def _decode(reader: _Reader, depth: int) -> Any:
    if depth > MAX_DEPTH:
        raise DecodeError("Variant is nested too deeply")
    header = reader.u32()
    type_id = header & _TYPE_MASK
    if type_id >= len(TYPE_NAMES):
        raise DecodeError(f"unknown Variant type {type_id}")
    name = TYPE_NAMES[type_id]
    wide = bool(header & _FLAG_64)

    if name == "Nil":
        return None
    if name == "bool":
        return bool(reader.u32())
    if name == "int":
        return struct.unpack("<q" if wide else "<i", reader.take(8 if wide else 4))[0]
    if name == "float":
        return _floats(reader, 1, wide)[0]
    if name == "String":
        return reader.string()
    if name == "StringName":
        return StringName(reader.string())
    if name in _FIXED:
        count, kind = _FIXED[name]
        if kind == "i":
            return Value(name, struct.unpack(f"<{count}i", reader.take(count * 4)))
        return Value(name, _floats(reader, count, wide and kind == "f"))
    if name == "NodePath":
        return _decode_node_path(reader)
    if name == "RID":
        return Rid(struct.unpack("<Q", reader.take(8))[0])
    if name == "Object":
        if not header & _FLAG_OBJECT_AS_ID:
            raise DecodeError("full objects are not sent over the debugger link")
        return ObjectId(struct.unpack("<Q", reader.take(8))[0])
    if name == "Callable":
        return CallableRef()
    if name == "Signal":
        signal_name = reader.string()
        return SignalRef(signal_name, struct.unpack("<Q", reader.take(8))[0])
    if name == "Dictionary":
        key = _container_type(reader, (header >> _DICT_KEY_SHIFT) & 0b11)
        value = _container_type(reader, (header >> _DICT_VALUE_SHIFT) & 0b11)
        count = reader.u32() & 0x7FFFFFFF  # bit 31 is the "shared" flag
        result = GodotDict(key=key, value=value)
        for _ in range(count):
            k = _decode(reader, depth + 1)
            result[_hashable(k)] = _decode(reader, depth + 1)
        return result
    if name == "Array":
        element = _container_type(reader, (header >> _ARRAY_KIND_SHIFT) & 0b11)
        count = reader.u32() & 0x7FFFFFFF
        return GodotArray((_decode(reader, depth + 1) for _ in range(count)), element=element)
    if name == "PackedByteArray":
        count = reader.i32()
        data = reader.take(count)
        reader.take((4 - count % 4) % 4)
        return data
    if name == "PackedStringArray":
        # Unlike a String, each entry's length counts its terminating NUL.
        count = reader.i32()
        return Packed(name, tuple(reader.string().removesuffix("\0") for _ in range(count)))
    if name in _PACKED:
        return _decode_packed(reader, name, wide)
    raise DecodeError(f"unhandled Variant type {name}")  # pragma: no cover


def _decode_node_path(reader: _Reader) -> NodePath:
    first = reader.u32()
    if not first & 0x80000000:
        raise DecodeError("old-format NodePath")
    names = first & 0x7FFFFFFF
    subnames = reader.u32()
    flags = reader.u32()
    if flags & 2:  # obsolete form: the property is carried as one more subname
        subnames += 1
    parts = [reader.string() for _ in range(names + subnames)]
    text = "/".join(parts[:names])
    if flags & 1:
        text = "/" + text
    for sub in parts[names:]:
        text += ":" + sub
    return NodePath(text)


def _decode_packed(reader: _Reader, name: str, wide: bool) -> Packed:
    count = reader.i32()
    if count < 0:
        raise DecodeError("negative packed array size")
    per, kind = _PACKED[name]
    if kind == "i":
        return Packed(name, struct.unpack(f"<{count}i", reader.take(count * 4)))
    if kind == "q":
        return Packed(name, struct.unpack(f"<{count}q", reader.take(count * 8)))
    if kind == "f32":
        return Packed(name, _floats(reader, count, False))
    if kind == "f64":
        return Packed(name, _floats(reader, count, True))
    element = {"PackedVector2Array": "Vector2", "PackedVector3Array": "Vector3",
               "PackedColorArray": "Color", "PackedVector4Array": "Vector4"}[name]
    flat = _floats(reader, count * per, wide and kind == "f")
    return Packed(name, tuple(Value(element, flat[i * per:(i + 1) * per]) for i in range(count)))


def _hashable(key: Any) -> Any:
    """Dictionary keys must be hashable in Python; an Array key becomes a tuple."""
    if isinstance(key, list):
        return tuple(_hashable(item) for item in key)
    if isinstance(key, dict):
        return tuple((k, _hashable(v)) for k, v in key.items())
    return key


# ---------------------------------------------------------------------------
# Encoding
# ---------------------------------------------------------------------------


def encode(value: Any) -> bytes:
    """Encode a value the way Godot's encode_variant would (objects as ids)."""
    out = bytearray()
    _encode(value, out, 0)
    return bytes(out)


def _put_string(text: str, out: bytearray) -> None:
    raw = text.encode("utf-8")
    out += struct.pack("<I", len(raw)) + raw + b"\0" * ((4 - len(raw) % 4) % 4)


def _container_header(kind: ContainerType | None, shift: int) -> int:
    return 0 if kind is None else kind.kind << shift


def _put_container(kind: ContainerType | None, out: bytearray) -> None:
    if kind is None:
        return
    if kind.kind == _KIND_BUILTIN:
        out += struct.pack("<I", kind.builtin)
    else:
        _put_string(kind.name, out)


def _fits_float32(number: float) -> bool:
    try:
        return _as_float32(number) == number
    except OverflowError:
        return False


def _encode(value: Any, out: bytearray, depth: int) -> None:
    if depth > MAX_DEPTH:
        raise ValueError("value is nested too deeply to encode")

    if value is None:
        out += struct.pack("<I", TYPE_IDS["Nil"])
    elif isinstance(value, bool):
        out += struct.pack("<II", TYPE_IDS["bool"], int(value))
    elif isinstance(value, int):
        if -(2 ** 31) <= value < 2 ** 31:
            out += struct.pack("<Ii", TYPE_IDS["int"], value)
        else:
            out += struct.pack("<Iq", TYPE_IDS["int"] | _FLAG_64, value)
    elif isinstance(value, float):
        # Godot sends a float as 32 bits when nothing is lost, else as a double.
        if _fits_float32(value):
            out += struct.pack("<If", TYPE_IDS["float"], value)
        else:
            out += struct.pack("<Id", TYPE_IDS["float"] | _FLAG_64, value)
    elif isinstance(value, StringName):
        out += struct.pack("<I", TYPE_IDS["StringName"])
        _put_string(value, out)
    elif isinstance(value, NodePath):
        _encode_node_path(value, out)
    elif isinstance(value, str):
        out += struct.pack("<I", TYPE_IDS["String"])
        _put_string(value, out)
    elif isinstance(value, Value):
        count, kind = _FIXED[value.type]
        if len(value.components) != count:
            raise ValueError(f"{value.type} takes {count} components, got {len(value.components)}")
        fmt = "i" if kind == "i" else "f"
        out += struct.pack(f"<I{count}{fmt}", TYPE_IDS[value.type], *value.components)
    elif isinstance(value, ObjectId):
        out += struct.pack("<IQ", TYPE_IDS["Object"] | _FLAG_OBJECT_AS_ID, value.id)
    elif isinstance(value, Rid):
        out += struct.pack("<IQ", TYPE_IDS["RID"], value.id)
    elif isinstance(value, SignalRef):
        out += struct.pack("<I", TYPE_IDS["Signal"])
        _put_string(value.name, out)
        out += struct.pack("<Q", value.object_id)
    elif isinstance(value, CallableRef):
        out += struct.pack("<I", TYPE_IDS["Callable"])
    elif isinstance(value, dict):
        key_type = getattr(value, "key_type", None)
        value_type = getattr(value, "value_type", None)
        header = (TYPE_IDS["Dictionary"] | _container_header(key_type, _DICT_KEY_SHIFT)
                  | _container_header(value_type, _DICT_VALUE_SHIFT))
        out += struct.pack("<I", header)
        _put_container(key_type, out)
        _put_container(value_type, out)
        out += struct.pack("<I", len(value))
        for key, item in value.items():
            _encode(list(key) if isinstance(key, tuple) and not isinstance(key, Value) else key,
                    out, depth + 1)
            _encode(item, out, depth + 1)
    elif isinstance(value, (list, tuple)):
        element = getattr(value, "element", None)
        out += struct.pack("<I", TYPE_IDS["Array"] | _container_header(element, _ARRAY_KIND_SHIFT))
        _put_container(element, out)
        out += struct.pack("<I", len(value))
        for item in value:
            _encode(item, out, depth + 1)
    elif isinstance(value, (bytes, bytearray)):
        out += struct.pack("<Ii", TYPE_IDS["PackedByteArray"], len(value))
        out += bytes(value) + b"\0" * ((4 - len(value) % 4) % 4)
    elif isinstance(value, Packed):
        _encode_packed(value, out)
    else:
        raise TypeError(f"cannot encode {type(value).__name__} as a Godot Variant")


def _encode_node_path(path: NodePath, out: bytearray) -> None:
    text = str(path)
    absolute = text.startswith("/")
    main, *subnames = (text[1:] if absolute else text).split(":")
    names = [part for part in main.split("/") if part]
    out += struct.pack("<IIII", TYPE_IDS["NodePath"], len(names) | 0x80000000,
                       len(subnames), 1 if absolute else 0)
    for part in names + subnames:
        _put_string(part, out)


def _encode_packed(value: Packed, out: bytearray) -> None:
    out += struct.pack("<Ii", TYPE_IDS[value.type], len(value.items))
    if value.type == "PackedStringArray":
        for text in value.items:
            _put_string(text + "\0", out)  # the length counts the NUL, as Godot writes it
        return
    kind = _PACKED[value.type][1]
    if kind == "i":
        out += struct.pack(f"<{len(value.items)}i", *value.items)
    elif kind == "q":
        out += struct.pack(f"<{len(value.items)}q", *value.items)
    elif kind == "f64":
        out += struct.pack(f"<{len(value.items)}d", *value.items)
    elif kind == "f32":
        out += struct.pack(f"<{len(value.items)}f", *value.items)
    else:
        flat = [c for item in value.items for c in item.components]
        out += struct.pack(f"<{len(flat)}f", *flat)


# ---------------------------------------------------------------------------
# Framing
# ---------------------------------------------------------------------------


def frame(value: Any) -> bytes:
    """A length-prefixed message as RemoteDebuggerPeerTCP sends and expects it."""
    payload = encode(value)
    if len(payload) > MAX_MESSAGE_BYTES:
        raise ValueError(f"message of {len(payload)} bytes exceeds the game's 8 MiB limit")
    return struct.pack("<I", len(payload)) + payload


# Thread::MAIN_ID. The game ignores a message addressed to a thread it does not have.
MAIN_THREAD = 1


def message(name: str, data: list | tuple = (), thread_id: int = MAIN_THREAD) -> bytes:
    """Frame a debugger message: ``[name, thread_id, data]``."""
    return frame([name, thread_id, list(data)])


# ---------------------------------------------------------------------------
# Text and JSON for agents
# ---------------------------------------------------------------------------


def _as_float32(number: float) -> float:
    return struct.unpack("<f", struct.pack("<f", number))[0]


def _component(number: float, kind: str) -> str:
    """A component as var_to_str writes it: whole numbers without ".0", otherwise the
    shortest text that reads back as the same value - at float32 precision for real_t
    and Color components, so 0.1f prints as 0.1 rather than 0.10000000149011612."""
    if kind == "i":
        return str(number)
    if number != number or number in (float("inf"), float("-inf")):
        return _scalar_float(number)
    if number == int(number) and abs(number) < 1e16:
        return str(int(number))
    single = kind in {"f", "c"}
    for precision in range(1, 18):
        text = f"{number:.{precision}g}"
        parsed = float(text)
        if (_as_float32(parsed) if single else parsed) == number:
            return text
    return repr(number)


def _scalar_float(number: float) -> str:
    if number != number:
        return "nan"
    if number in (float("inf"), float("-inf")):
        return "inf" if number > 0 else "-inf"
    if number == 0:
        return "0.0"  # var_to_str writes -0.0 as 0.0 too
    return repr(number)


def _quote(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def to_text(value: Any) -> str:
    """Godot literal text for a value, as var_to_str writes it."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return _scalar_float(value)
    if isinstance(value, StringName):
        return "&" + _quote(value)
    if isinstance(value, NodePath):
        return f"NodePath({_quote(value)})"
    if isinstance(value, str):
        return _quote(value)
    if isinstance(value, Value):
        kind = _FIXED[value.type][1]
        return f"{value.type}({', '.join(_component(c, kind) for c in value.components)})"
    if isinstance(value, ObjectId):
        return f"Object(#{value.id})" if value.id else "null"
    if isinstance(value, Rid):
        return f"RID({value.id})"
    if isinstance(value, SignalRef):
        return f"Signal(#{value.object_id}, {_quote(value.name)})"
    if isinstance(value, CallableRef):
        return "Callable()"
    if isinstance(value, (bytes, bytearray)):
        return f"PackedByteArray({', '.join(str(b) for b in value)})"
    if isinstance(value, Packed):
        if value.type == "PackedStringArray":
            return f"{value.type}({', '.join(_quote(s) for s in value.items)})"
        kind = _PACKED[value.type][1]
        if kind in {"i", "q"}:
            parts = [str(n) for n in value.items]
        elif kind in {"f32", "f64"}:
            parts = [_component(n, "f" if kind == "f32" else "d") for n in value.items]
        else:
            parts = [_component(c, "f") for item in value.items for c in item.components]
        return f"{value.type}({', '.join(parts)})"
    if isinstance(value, dict):
        body = ", ".join(f"{to_text(k)}: {to_text(v)}" for k, v in value.items())
        key_type, value_type = getattr(value, "key_type", None), getattr(value, "value_type", None)
        if key_type or value_type:
            names = [t.text() if t else "Variant" for t in (key_type, value_type)]
            return f"Dictionary[{names[0]}, {names[1]}]({{{body}}})"
        return f"{{{body}}}"
    if isinstance(value, (list, tuple)):
        body = ", ".join(to_text(item) for item in value)
        element = getattr(value, "element", None)
        return f"Array[{element.text()}]([{body}])" if element else f"[{body}]"
    return repr(value)


def to_json(value: Any) -> Any:
    """A value an agent can read: JSON scalars stay scalars, the rest is Godot text.

    Objects become ``{"object_id": n}`` so the id can be passed back to other tools.
    """
    if value is None or isinstance(value, (bool, int)):
        return value
    if isinstance(value, float):
        return value if value == value and abs(value) != float("inf") else _scalar_float(value)
    if isinstance(value, ObjectId):
        return {"object_id": value.id} if value.id else None
    if isinstance(value, str) and not isinstance(value, (StringName, NodePath)):
        return str(value)
    if isinstance(value, dict):
        return {(k if isinstance(k, str) else to_text(k)): to_json(v) for k, v in value.items()}
    if isinstance(value, list):
        return [to_json(item) for item in value]
    return to_text(value)


_LITERAL = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$", re.DOTALL)


def from_json(value: Any, type_name: str | None = None) -> Any:
    """Turn what an agent passed into a value of ``type_name`` (or a plain one).

    Accepts JSON scalars, lists of components (``[1, 2]`` for a Vector2), Godot
    literal text (``"Vector2(1, 2)"``), or the explicit form
    ``{"type": "Vector2", "value": [1, 2]}``. Raises ValueError when it cannot.
    """
    if isinstance(value, dict) and "type" in value and "value" in value:
        return from_json(value["value"], str(value["type"]))
    if isinstance(value, dict) and "object_id" in value:
        return ObjectId(int(value["object_id"]))
    if type_name is None or type_name in {"Nil", "Variant", ""}:
        if isinstance(value, list):
            return [from_json(item) for item in value]
        if isinstance(value, dict):
            return {k: from_json(v) for k, v in value.items()}
        return value

    if type_name in _FIXED:
        count, kind = _FIXED[type_name]
        components = _components_of(value, type_name)
        if len(components) != count:
            raise ValueError(f"{type_name} takes {count} components, got {len(components)}")
        cast = int if kind == "i" else float
        return Value(type_name, tuple(cast(c) for c in components))
    if type_name == "bool":
        if isinstance(value, str):
            if value.lower() not in {"true", "false"}:
                raise ValueError(f"not a bool: {value!r}")
            return value.lower() == "true"
        return bool(value)
    if type_name == "int":
        return int(value)
    if type_name == "float":
        return float(value)
    if type_name == "String":
        return str(value)
    if type_name == "StringName":
        return StringName(str(value))
    if type_name == "NodePath":
        text = str(value)
        match = _LITERAL.match(text)
        if match and match.group(1) == "NodePath":
            text = match.group(2).strip().strip('"')
        return NodePath(text)
    if type_name == "Array":
        return [from_json(item) for item in _as_list(value)]
    if type_name == "Dictionary":
        if not isinstance(value, dict):
            raise ValueError("a Dictionary needs a JSON object")
        return {k: from_json(v) for k, v in value.items()}
    if type_name == "PackedByteArray":
        return bytes(int(b) for b in _as_list(value))
    if type_name == "PackedStringArray":
        return Packed(type_name, tuple(str(s) for s in _as_list(value)))
    if type_name in _PACKED:
        per, kind = _PACKED[type_name]
        items = _as_list(value)
        if per == 1:
            cast = int if kind in {"i", "q"} else float
            return Packed(type_name, tuple(cast(n) for n in items))
        element = type_name.removeprefix("Packed").removesuffix("Array")
        return Packed(type_name, tuple(from_json(item, element) for item in items))
    return value


def _components_of(value: Any, type_name: str) -> list:
    if isinstance(value, Value):
        return list(value.components)
    if isinstance(value, (list, tuple)):
        return list(value)
    if isinstance(value, dict):
        for keys in ("xyzw", "rgba"):
            if keys[0] in value:
                return [value[k] for k in keys if k in value]
    if isinstance(value, str):
        if type_name == "Color" and value.startswith("#"):
            return list(_hex_color(value))
        match = _LITERAL.match(value)
        if match:
            if match.group(1) != type_name:
                raise ValueError(f"expected a {type_name}, got {match.group(1)}")
            return [float(part) for part in re.split(r"[,\s]+", match.group(2).strip()) if part]
    raise ValueError(f"cannot read {value!r} as a {type_name}")


def _hex_color(text: str) -> tuple:
    digits = text.lstrip("#")
    if len(digits) not in (6, 8):
        raise ValueError(f"not a colour: {text!r}")
    channels = [int(digits[i:i + 2], 16) / 255 for i in range(0, len(digits), 2)]
    return tuple(channels + [1.0] * (4 - len(channels)))


def _as_list(value: Any) -> list:
    if isinstance(value, Packed):
        return list(value.items)
    if isinstance(value, (list, tuple, bytes)):
        return list(value)
    raise ValueError(f"expected a list, got {type(value).__name__}")
